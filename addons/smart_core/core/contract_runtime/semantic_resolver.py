# -*- coding: utf-8 -*-
"""Resolve a field to the component key the frontend renders.

Declaration authority: ``contracts/registry/semantic.yaml`` (what a field means)
plus ``contracts/registry/component.yaml`` (which component renders it).  The
runtime image does not ship ``contracts/``, so ``semantic_registry_generated``
carries the declaration into the addon; that carrier is regenerated by
``scripts/contract/generate_semantic_registry.py`` and checked for drift by
``make verify.semantic.registry.lint``.

This module replaces the private ``_component_key`` mapping that used to hold
half of the vocabulary inside the assembler
(FE-CONTRACT-RUNTIME-00 gap G1).  The rules are data: a new business field that
hits an existing rule, or that declares ``semantic`` explicitly, needs no new
mapping code on either side.

Two resolution sources are reported so a caller can tell a deliberate
declaration from a derived guess:

* ``declared`` - the field descriptor carries an explicit ``semantic``;
* ``derived``  - the ordered derivation rules resolved it from field facts.

There is deliberately no separate "readonly component": a component's read
profile is part of its registration (``render_profiles``), so declaring a second
key per semantic would create an undeclared, unconsumed capability.
"""

from __future__ import annotations

import logging
from typing import Any

from .semantic_registry_generated import (
    DERIVATION_DEFAULT,
    DERIVATION_RULES,
    SEMANTIC_COMPONENTS,
)

_logger = logging.getLogger(__name__)

SOURCE_DECLARED = "declared"
SOURCE_DERIVED = "derived"

# Canonical name of the one-time compatibility signal.  Naming it here keeps the
# event string out of call sites and lets a test assert it fires exactly once.
DEPRECATION_EVENT = "deprecated_component_key_usage"

FALLBACK_SEMANTIC = DERIVATION_DEFAULT
FALLBACK_COMPONENT_KEY = SEMANTIC_COMPONENTS[DERIVATION_DEFAULT]

_deprecation_reported = False


def _text(value: Any) -> str:
    return str(value if value is not None else "").strip()


def field_type_of(field: Any) -> str:
    descriptor = field if isinstance(field, dict) else {}
    return _text(descriptor.get("ttype") or descriptor.get("type")).lower()


def _matches(rule: dict, widget: str, field_type: str) -> bool:
    field_types = rule.get("field_types")
    if field_types and field_type not in field_types:
        return False
    widgets = rule.get("widgets")
    if widgets and widget not in widgets:
        return False
    excluded = rule.get("widgets_exclude")
    if excluded and widget in excluded:
        return False
    suffix = rule.get("widget_suffix")
    if suffix and not widget.endswith(_text(suffix)):
        return False
    return True


def derive_semantic(field: Any = None, widget_type: str = "") -> str:
    """First ordered rule whose conditions all hold, else the declared default."""
    widget = _text(widget_type).lower()
    field_type = field_type_of(field)
    for rule in DERIVATION_RULES:
        semantic = _text(rule.get("semantic"))
        if semantic and _matches(rule, widget, field_type):
            return semantic
    return FALLBACK_SEMANTIC


def resolve(field: Any = None, widget_type: str = "") -> dict[str, str]:
    """Resolve to ``{semantic, componentKey, semanticSource}``.

    An explicit ``semantic`` on the descriptor wins.  An unknown declared
    semantic cannot be rendered, so it is reported as a contract defect and the
    derivation result is used instead of a component the frontend never
    registered.
    """
    descriptor = field if isinstance(field, dict) else {}
    declared = _text(descriptor.get("semantic")).lower()
    if declared:
        component_key = SEMANTIC_COMPONENTS.get(declared)
        if component_key:
            return {
                "semantic": declared,
                "componentKey": component_key,
                "semanticSource": SOURCE_DECLARED,
            }
        _logger.error(
            "contract_semantic_undeclared semantic=%s declared_by=%s; falling back to the "
            "derivation default. Fix the declaration in contracts/registry/semantic.yaml.",
            declared,
            _text(descriptor.get("name")) or "<unnamed field>",
        )
    semantic = derive_semantic(descriptor, widget_type)
    return {
        "semantic": semantic,
        "componentKey": SEMANTIC_COMPONENTS.get(semantic, FALLBACK_COMPONENT_KEY),
        "semanticSource": SOURCE_DERIVED,
    }


def component_key(widget_type: str = "", field: Any = None) -> str:
    """The registry-driven component key: the authority path."""
    return resolve(field, widget_type)["componentKey"]


def component_key_for_semantic(semantic: str) -> str:
    """Component key a declared semantic resolves to (``''`` when undeclared).

    For a caller that already knows the meaning and only needs the registry to
    name the renderer, e.g. a display-only layout block.
    """
    return SEMANTIC_COMPONENTS.get(_text(semantic).lower(), "")


def semantic_of(widget_type: str = "", field: Any = None) -> str:
    """The resolved semantic (``declared`` or ``derived``)."""
    return resolve(field, widget_type)["semantic"]


def legacy_component_key(widget_type: str = "", field: Any = None) -> str:
    """Deprecated compatibility shim for the removed private mapping.

    Kept so an unmigrated caller keeps working, but it reports
    ``DEPRECATION_EVENT`` once per process: component selection belongs to the
    contract registry, and a caller reaching this shim is choosing the legacy
    entry point instead of :func:`component_key`.
    """
    global _deprecation_reported
    if not _deprecation_reported:
        _deprecation_reported = True
        _logger.warning(
            "%s: the assembler-private component mapping is gone; resolve component keys "
            "through contracts/registry/semantic.yaml (call semantic_resolver.component_key).",
            DEPRECATION_EVENT,
        )
    return component_key(widget_type, field)
