# -*- coding: utf-8 -*-
"""Resolve a field to the component key the frontend renders.

Declaration authority: ``contracts/registry/semantic.yaml`` (what a field means)
plus ``contracts/registry/component.yaml`` (which component renders it).  The
runtime image does not ship ``contracts/``, so ``semantic_registry_generated``
carries the declaration into the addon; that carrier is regenerated by
``scripts/contract/generate_semantic_registry.py`` and checked for drift by
``make verify.semantic.registry.lint``.

This module replaces the private ``_component_key`` mapping that used to hold
half of the vocabulary inside the assembler
(FE-CONTRACT-RUNTIME-00 gap G1).  The rules are data: a new business field that
hits an existing rule, or that declares ``semantic`` explicitly, needs no new
mapping code on either side.

Two resolution sources are reported so a caller can tell a deliberate
declaration from a derived guess:

* ``declared`` - the field descriptor carries an explicit ``semantic``;
* ``derived``  - the ordered derivation rules resolved it from field facts.

There is deliberately no separate "readonly component": a component's read
profile is part of its registration (``render_profiles``), so declaring a second
key per semantic would create an undeclared, unconsumed capability.
"""

from __future__ import annotations

import logging
from typing import Any

from .domain_field_semantics_generated import DOMAIN_FIELD_SEMANTICS
from .semantic_registry_generated import (
    DERIVATION_DEFAULT,
    DERIVATION_RULES,
    SEMANTIC_COMPONENTS,
)

_logger = logging.getLogger(__name__)

SOURCE_DECLARED = "declared"
SOURCE_PROJECTED = "projected"
SOURCE_DERIVED = "derived"

# The descriptor key the assembler writes when it annotates a field from the
# contract carrier projected out of the parsed model/view facts, so
# :func:`resolve` can report that projection distinctly from a declaration a
# runtime extension made itself.  Naming it here keeps the string out of call
# sites.
ORIGIN_KEY = "semanticOrigin"
ORIGIN_PROJECTED = "projected"

# Native Odoo widget names that are themselves the semantic signal: the rules in
# ``contracts/registry/semantic.yaml`` match these spellings directly, so they
# must survive widget canonicalisation.  ``statusbar`` folded into the generic
# ``display`` token would erase the fact that a selection field is a status, and
# the status rule would become unreachable.
SEMANTIC_WIDGET_HINTS = frozenset({
    "monetary", "percentage", "percentpie", "float_time", "statusbar", "badge",
})

# Canonical name of the one-time compatibility signal.  Naming it here keeps the
# event string out of call sites and lets a test assert it fires exactly once.
DEPRECATION_EVENT = "deprecated_component_key_usage"

FALLBACK_SEMANTIC = DERIVATION_DEFAULT
FALLBACK_COMPONENT_KEY = SEMANTIC_COMPONENTS[DERIVATION_DEFAULT]

_deprecation_reported = False


def _text(value: Any) -> str:
    return str(value if value is not None else "").strip()


def field_type_of(field: Any) -> str:
    descriptor = field if isinstance(field, dict) else {}
    return _text(descriptor.get("ttype") or descriptor.get("type")).lower()


def _matches(rule: dict, widget: str, field_type: str) -> bool:
    field_types = rule.get("field_types")
    if field_types and field_type not in field_types:
        return False
    widgets = rule.get("widgets")
    if widgets and widget not in widgets:
        return False
    excluded = rule.get("widgets_exclude")
    if excluded and widget in excluded:
        return False
    suffix = rule.get("widget_suffix")
    if suffix and not widget.endswith(_text(suffix)):
        return False
    return True


def derive_semantic(field: Any = None, widget_type: str = "") -> str:
    """First ordered rule whose conditions all hold, else the declared default."""
    widget = _text(widget_type).lower()
    field_type = field_type_of(field)
    for rule in DERIVATION_RULES:
        semantic = _text(rule.get("semantic"))
        if semantic and _matches(rule, widget, field_type):
            return semantic
    return FALLBACK_SEMANTIC


def semantic_widget_type(native_widget: str = "", canonical_widget_type: str = "") -> str:
    """The widget token the derivation rules are evaluated against.

    One implementation for the page assembler and for the projection generator,
    so the component a page renders and the component the contract carrier
    records can never come from two different readings of the same field facts.
    """
    native = _text(native_widget).lower()
    if native in SEMANTIC_WIDGET_HINTS:
        return native
    return _text(canonical_widget_type).lower()


def resolve(field: Any = None, widget_type: str = "") -> dict[str, str]:
    """Resolve to ``{semantic, componentKey, semanticSource}``.

    An explicit ``semantic`` on the descriptor wins.  An unknown declared
    semantic cannot be rendered, so it is reported as a contract defect and the
    derivation result is used instead of a component the frontend never
    registered.
    """
    descriptor = field if isinstance(field, dict) else {}
    declared = _text(descriptor.get("semantic")).lower()
    if declared:
        component_key = SEMANTIC_COMPONENTS.get(declared)
        if component_key:
            origin = _text(descriptor.get(ORIGIN_KEY)).lower()
            return {
                "semantic": declared,
                "componentKey": component_key,
                "semanticSource": SOURCE_PROJECTED if origin == ORIGIN_PROJECTED else SOURCE_DECLARED,
            }
        _logger.error(
            "contract_semantic_undeclared semantic=%s declared_by=%s; falling back to the "
            "derivation default. Fix the declaration in contracts/registry/semantic.yaml.",
            declared,
            _text(descriptor.get("name")) or "<unnamed field>",
        )
    semantic = derive_semantic(descriptor, widget_type)
    return {
        "semantic": semantic,
        "componentKey": SEMANTIC_COMPONENTS.get(semantic, FALLBACK_COMPONENT_KEY),
        "semanticSource": SOURCE_DERIVED,
    }


def component_key(widget_type: str = "", field: Any = None) -> str:
    """The registry-driven component key: the authority path."""
    return resolve(field, widget_type)["componentKey"]


def component_key_for_semantic(semantic: str) -> str:
    """Component key a declared semantic resolves to (``''`` when undeclared).

    For a caller that already knows the meaning and only needs the registry to
    name the renderer, e.g. a display-only layout block.
    """
    return SEMANTIC_COMPONENTS.get(_text(semantic).lower(), "")


def projected_field_semantics(model: str, field_name: str) -> str:
    """The contract semantic of a model field, derived from model/view facts.

    The public backend input is the model metadata plus the parsed view arch, so
    the meaning of a field is read from those facts by
    ``contracts/registry/semantic.yaml`` and projected into the runtime carrier
    ``domain_field_semantics_generated`` (the runtime image does not ship
    ``contracts/``).  Nothing is authored by hand, so there is no second input
    for the meaning that could drift out of step with the model.  Callers
    annotate the field descriptor with the result; the descriptor stays the
    single input of :func:`resolve`.
    """
    entity = _text(model).lower()
    name = _text(field_name)
    if not entity or not name:
        return ""
    declared = DOMAIN_FIELD_SEMANTICS.get(entity) or {}
    return _text(declared.get(name)).lower()


def annotate_projected_semantics(model: str, fields: Any) -> int:
    """Annotate field descriptors with the projected contract semantic.

    Returns how many descriptors were annotated.  A descriptor that already
    carries an explicit ``semantic`` keeps it: a runtime extension is a more
    specific declaration than the entity default, and silently overwriting it
    would make the runtime observation unrepresentable.  A semantic that
    ``semantic.yaml`` does not declare is never written, so this can only add
    values the resolver can honour.
    """
    annotated = 0
    rows = fields if isinstance(fields, (list, tuple)) else []
    for row in rows:
        if not isinstance(row, dict):
            continue
        semantic = projected_field_semantics(model, _text(row.get("name") or row.get("field") or row.get("fieldCode")))
        if not semantic or _text(row.get("semantic")) or semantic not in SEMANTIC_COMPONENTS:
            continue
        row["semantic"] = semantic
        row[ORIGIN_KEY] = ORIGIN_PROJECTED
        annotated += 1
    return annotated


def semantic_of(widget_type: str = "", field: Any = None) -> str:
    """The resolved semantic (``declared`` or ``derived``)."""
    return resolve(field, widget_type)["semantic"]


def legacy_component_key(widget_type: str = "", field: Any = None) -> str:
    """Deprecated compatibility shim for the removed private mapping.

    Kept so an unmigrated caller keeps working, but it reports
    ``DEPRECATION_EVENT`` once per process: component selection belongs to the
    contract registry, and a caller reaching this shim is choosing the legacy
    entry point instead of :func:`component_key`.
    """
    global _deprecation_reported
    if not _deprecation_reported:
        _deprecation_reported = True
        _logger.warning(
            "%s: the assembler-private component mapping is gone; resolve component keys "
            "through contracts/registry/semantic.yaml (call semantic_resolver.component_key).",
            DEPRECATION_EVENT,
        )
    return component_key(widget_type, field)


# The page contract declares each component it uses by identity plus version.
# The version is one fact for the whole runtime: a page handler, a form
# finalizer or a construction-product extension must not each carry their own
# copy, because the frontend rejects a registry entry without a version and a
# second copy is exactly the driftable vocabulary this module removed.
COMPONENT_CONTRACT_VERSION = "1.0"


def component_registry(component_keys: Any) -> dict[str, dict[str, str]]:
    """Declare a page's component identities from the keys it renders.

    The single builder for every runtime producer, so a page assembled by the
    generic assembler, a page extended by a product-layer normalizer and a page
    handler that adds a control all publish the identical identity fact.

    Fail-closed: a key no carrier declares is reported and left out, so a page
    cannot publish an identity the frontend has no registration for.  The
    frontend rejects such a key anyway (``PROFESSIONAL_COMPONENT_UNREGISTERED``),
    and dropping it here makes the contract say the same thing the renderer
    enforces instead of shipping a registration that cannot resolve.
    """
    declared = set(SEMANTIC_COMPONENTS.values())
    keys = component_keys if isinstance(component_keys, (list, tuple, set, frozenset)) else []
    registry: dict[str, dict[str, str]] = {}
    for key in sorted({_text(k) for k in keys if _text(k)}):
        if key not in declared:
            _logger.error(
                "contract_component_undeclared componentKey=%s; contracts/registry/component.yaml does not "
                "declare it, so the key is not published. Declare the field's semantic instead.",
                key,
            )
            continue
        registry[key] = {"version": COMPONENT_CONTRACT_VERSION}
    return registry
